/**
 * Validate URL format and optionally check for specific schemes
 */
export function validateUrl(url: string, schemes?: string[]): string {
	try {
		const parsed = new URL(url);
		if (!parsed.hostname) {
			throw new Error(`Invalid URL format: ${url}`);
		}
		if (schemes && schemes.length > 0 && !schemes.includes(parsed.protocol.replace(':', ''))) {
			throw new Error(`URL has invalid scheme: ${url} (expected one of ${schemes.join(', ')})`);
		}
		return url;
	} catch (error: any) {
		throw new Error(`Invalid URL: ${url} - ${error.message}`);
	}
}

/**
 * Validate that float is within specified range
 */
export function validateFloatRange(value: number, minVal: number, maxVal: number): number {
	if (value < minVal || value > maxVal) {
		throw new Error(`Value ${value} outside of range ${minVal}-${maxVal}`);
	}
	return value;
}

/**
 * Validate that arg is a valid CLI argument
 */
export function validateCliArg(arg: string): string {
	if (!arg.startsWith('--')) {
		throw new Error(`Invalid CLI argument: ${arg} (should start with --, e.g. --some-key="some value here")`);
	}
	return arg;
}

