let cachedDisplaySize: ViewportSize | null = null;

/**
 * Get the display size (cross-platform)
 */
export function getDisplaySize(): ViewportSize | null {
	if (cachedDisplaySize !== null) {
		return cachedDisplaySize;
	}

	// Try platform-specific detection
	try {
		const platform = os.platform();

		if (platform === 'darwin') {
			// macOS - would need native bindings, fall through to default
			// Could use 'node-mac-screen-size' package or electron screen API
		} else if (platform === 'win32' || platform === 'linux') {
			// Windows/Linux - would need screeninfo equivalent
			// Could use 'screeninfo' via Python bridge or electron screen API
		}
	} catch {
		// Fall through to default
	}

	console.debug('No display size detected, using default 1920x1080');
	cachedDisplaySize = { width: 1920, height: 1080 };
	return cachedDisplaySize;
}

/**
 * Returns recommended x, y offsets for window positioning
 */
export function getWindowAdjustments(): [number, number] {
	const platform = os.platform();

	if (platform === 'darwin') {
		// macOS has a small title bar, no border
		return [-4, 24];
	} else if (platform === 'win32') {
		// Windows has a border on the left
		return [-8, 0];
	} else {
		// Linux
		return [0, 0];
	}
}

